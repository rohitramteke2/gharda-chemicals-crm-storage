import FarmerService from '../services/FarmerService.js';
import logger        from '../utils/logger.js';

class AppError extends Error {
    constructor(message, statusCode, code) {
        super(message);
        this.statusCode = statusCode;
        this.code       = code;
    }
}

/**
 * FarmerController
 * ────────────────
 * All endpoints for /api/v1/farmers
 */
class FarmerController {

    // ── GET /farmers ──────────────────────────────────────────────────────
    /**
     * List + search farmers — paginated, all filters, full location details.
     *
     * Query params:
     *   page         {number}  default: 1
     *   per_page     {number}  default: 50, max: 200
     *   name         {string}  partial match — searches farmer name
     *   mobile       {string}  exact match
     *   category     {string}  exact  "A" | "A+" | "A++" | "B"
     *   market_id    {number}  exact
     *   village_id   {number}  exact
     *   state_id     {number}  filter all farmers in a state
     *   zone_id      {number}  filter all farmers in a zone
     *   region_id    {number}  filter all farmers in a region
     *   territory_id {number}  filter all farmers in a territory
     *
     * Response includes full location details:
     *   farmer_name, mobile, category,
     *   market_name, village_name, territory_name,
     *   region_name, state_name, zone_name
     */
    async list(req, res, next) {
        try {
            const {
                page, per_page,
                name, mobile, category,
                market_id, village_id,
                state_id, zone_id, region_id, territory_id,
            } = req.query;

            const result = await FarmerService.list({
                page, per_page,
                name, mobile, category,
                market_id, village_id,
                state_id, zone_id, region_id, territory_id,
            });

            res.json({ success: true, ...result });
        } catch (err) { next(err); }
    }

    // ── GET /farmers/:id ──────────────────────────────────────────────────
    /**
     * Get a single farmer by id — includes full location details.
     */
    async getOne(req, res, next) {
        try {
            const { id } = req.params;

            if (!id || isNaN(Number(id))) {
                throw new AppError('id must be a valid number.', 400, 'VALIDATION_ERROR');
            }

            const farmer = await FarmerService.getById(id);

            if (!farmer) {
                throw new AppError(`Farmer with id ${id} not found.`, 404, 'NOT_FOUND');
            }

            res.json({ success: true, data: farmer });
        } catch (err) { next(err); }
    }

    // ── POST /farmers ──────────────────────────────────────────────────────
    /**
     * Create a new farmer.
     *
     * Body (JSON):
     *   name        {string}  required
     *   mobile      {string}  optional
     *   category    {string}  optional  "A" | "A+" | "A++" | "B"
     *   market_id   {number}  optional
     *   village_id  {number}  optional
     *
     * Response returns the body you sent + id, created_at, updated_at:
     * {
     *   success: true,
     *   data: {
     *     id, created_at, updated_at,   ← generated by DB
     *     name, mobile, category, market_id, village_id  ← echoed from body
     *   }
     * }
     */
    async create(req, res, next) {
        try {
            const data = req.body;

            if (!data || typeof data !== 'object' || Array.isArray(data)) {
                throw new AppError('Request body must be a JSON object.', 400, 'VALIDATION_ERROR');
            }
            if (!data.name || !String(data.name).trim()) {
                throw new AppError('name is required.', 400, 'VALIDATION_ERROR');
            }

            const { id: _i, created_at: _c, updated_at: _u, ...payload } = data;

            const inserted = await FarmerService.create(payload);

            logger.info('FarmerController: farmer created', { id: inserted?.id });

            // Return body fields + DB-generated fields together
            res.status(201).json({
                success: true,
                data: {
                    id:         inserted.id,
                    created_at: inserted.created_at,
                    updated_at: inserted.updated_at,
                    // echo back what was sent
                    name:       payload.name,
                    mobile:     payload.mobile     ?? null,
                    category:   payload.category   ?? null,
                    market_id:  payload.market_id  ?? null,
                    village_id: payload.village_id ?? null,
                },
            });
        } catch (err) { next(err); }
    }

    // ── PATCH /farmers/:id ─────────────────────────────────────────────────
    /**
     * Partially update a farmer.
     * Only send the fields you want to change.
     * Updatable: name, mobile, category, market_id, village_id
     */
    async update(req, res, next) {
        try {
            const { id } = req.params;

            if (!id || isNaN(Number(id))) {
                throw new AppError('id must be a valid number.', 400, 'VALIDATION_ERROR');
            }

            const data = req.body;

            if (!data || typeof data !== 'object' || Array.isArray(data)) {
                throw new AppError('Request body must be a JSON object.', 400, 'VALIDATION_ERROR');
            }
            if (!Object.keys(data).length) {
                throw new AppError('Request body is empty — provide at least one field to update.', 400, 'VALIDATION_ERROR');
            }

            const { id: _i, created_at: _c, updated_at: _u, ...payload } = data;

            const updated = await FarmerService.update(id, payload);

            if (!updated) {
                throw new AppError(`Farmer with id ${id} not found.`, 404, 'NOT_FOUND');
            }

            logger.info('FarmerController: farmer updated', { id });
            res.json({ success: true, data: updated });
        } catch (err) { next(err); }
    }

    // ── POST /farmers/sync ────────────────────────────────────────────────────
    async syncFromCRM(req, res, next) {
        try {
            logger.info('FarmerController: CRM sync triggered');
            const result = await FarmerService.syncFromCRM();
            res.json({ success: true, ...result, message: `Synced ${result.synced} farmers from Zoho CRM (${result.inserted} inserted, ${result.updated} updated, ${result.skipped} skipped).` });
        } catch (err) { next(err); }
    }

    // ── DELETE /farmers/:id ────────────────────────────────────────────────────
    /**
     * Permanently delete a farmer.
     */
    async remove(req, res, next) {
        try {
            const { id } = req.params;

            if (!id || isNaN(Number(id))) {
                throw new AppError('id must be a valid number.', 400, 'VALIDATION_ERROR');
            }

            const deleted = await FarmerService.remove(id);

            if (!deleted) {
                throw new AppError(`Farmer with id ${id} not found.`, 404, 'NOT_FOUND');
            }

            logger.info('FarmerController: farmer deleted', { id });
            res.json({ success: true, message: `Farmer ${id} deleted.`, data: deleted });
        } catch (err) { next(err); }
    }
}

export default new FarmerController();